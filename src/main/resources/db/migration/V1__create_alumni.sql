CREATE TABLE alumni (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        linkedin_url VARCHAR(600) NOT NULL UNIQUE,
                        name VARCHAR(300) NOT NULL,
                        role_title VARCHAR(300) NOT NULL,
                        university VARCHAR(300) NOT NULL,
                        location VARCHAR(300),
                        linkedin_headline VARCHAR(2000),
                        passout_year INTEGER,
                        CHECK (
                            passout_year IS NULL
                                OR passout_year BETWEEN 1900 AND 2100
                            )
);